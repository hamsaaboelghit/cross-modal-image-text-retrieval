"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { ArrowLeft, BarChart3, BrainCircuit, Database, Layers3 } from "lucide-react";

type MetricSet = Record<string, number | undefined>;
type ModelMetric = {
  name?: string;
  experiment?: string;
  model_type?: string;
  encoder_type?: string | null;
  text_to_image?: MetricSet;
  image_to_text?: MetricSet;
  num_images?: number;
  embedding_dim?: number;
  test_set_used?: boolean;
  source?: string;
};
type MetricsPayload = { available?: boolean; message?: string; source?: string; models?: ModelMetric[] };
const API_BASE = (process.env.NEXT_PUBLIC_API_BASE_URL || "http://127.0.0.1:8000").replace(/\/$/, "");
const ks = ["recall@1", "recall@5", "recall@10"];

function MetricBars({ title, metrics }: {title: string; metrics?: MetricSet}) {
  return <div className="rounded-2xl border border-[#e9e7df] bg-[#fbfbf9] p-5">
    <h3 className="text-sm font-extrabold">{title}</h3>
    <div className="mt-5 space-y-4">
      {ks.map(key => {
        const value = metrics?.[key];
        const valid = typeof value === "number" && Number.isFinite(value);
        const percent = valid ? Math.max(0, Math.min(1, value)) * 100 : 0;
        return <div key={key}>
          <div className="mb-1.5 flex justify-between text-[10px] font-bold text-[#858895]"><span>{key.toUpperCase()}</span><span>{valid ? `${(value * 100).toFixed(2)}%` : "Not recorded"}</span></div>
          <div className="h-2 overflow-hidden rounded-full bg-[#eae8e2]"><div className="h-full rounded-full bg-[#7770e8]" style={{width:`${percent}%`}}/></div>
        </div>;
      })}
    </div>
  </div>;
}

export default function ComparePage() {
  const [data, setData] = useState<MetricsPayload | null>(null);
  const [error, setError] = useState("");
  useEffect(() => {
    let active = true;
    fetch(`${API_BASE}/metrics`)
      .then(async response => {
        if (!response.ok) throw new Error("Could not load evaluation metrics.");
        return response.json();
      })
      .then(payload => { if (active) setData(payload); })
      .catch(err => { if (active) setError(err instanceof Error ? err.message : "Metrics API unavailable."); });
    return () => { active = false; };
  }, []);

  const models = Array.isArray(data?.models) ? data.models : [];
  return (
    <main className="min-h-screen bg-[#f7f7f4] text-[#171b2b]">
      <header className="mx-auto flex max-w-[1280px] items-center justify-between px-5 py-6 sm:px-8">
        <Link href="/" className="flex items-center gap-3"><span className="grid h-10 w-10 place-items-center rounded-xl bg-[#242943] text-[#d9ff70]"><BrainCircuit size={21}/></span><span className="text-sm font-black">vision<span className="text-[#7770e8]">match</span></span></Link>
        <Link href="/" className="inline-flex items-center gap-2 rounded-full border border-[#e6e4dc] bg-white px-4 py-2.5 text-xs font-bold"><ArrowLeft size={14}/> Back to search</Link>
      </header>
      <section className="mx-auto max-w-[1180px] px-5 pb-20 pt-10 sm:px-8">
        <p className="text-[10px] font-extrabold uppercase tracking-[2px] text-[#7770e8]">Evaluation dashboard</p>
        <h1 className="mt-4 text-4xl font-black tracking-[-2px] sm:text-6xl">Model insights.</h1>
        <p className="mt-4 max-w-xl text-sm leading-7 text-[#858895]">Recall@K charts are populated from the saved validation evaluation artifacts generated by the project's evaluator. No illustrative scores are displayed.</p>
        <div className="mt-10 grid gap-4 sm:grid-cols-3">
          {[{label:"Dataset",value:"Flickr30k",icon:Database},{label:"Image encoder",value:"ResNet50",icon:Layers3},{label:"Retrieval directions",value:"2",icon:BarChart3}].map(item=><div key={item.label} className="rounded-2xl border border-[#e8e6df] bg-white p-5"><item.icon size={20} className="text-[#7770e8]"/><p className="mt-4 text-[10px] font-extrabold uppercase tracking-wider text-[#a0a1aa]">{item.label}</p><p className="mt-2 text-xl font-black">{item.value}</p></div>)}
        </div>
        <section className="mt-8 rounded-[26px] border border-[#e8e6df] bg-white p-6 sm:p-8">
          <div className="flex flex-wrap items-center justify-between gap-3"><div><p className="text-[10px] font-extrabold uppercase tracking-widest text-[#7770e8]">Saved validation outputs</p><h2 className="mt-2 text-xl font-black">Recall@K comparison</h2></div><span className="rounded-full bg-[#f4f2ff] px-3 py-2 text-[10px] font-bold text-[#665fc5]">{models.length} model result(s)</span></div>
          {error && <p role="alert" className="mt-6 rounded-xl bg-red-50 p-4 text-sm text-red-700">{error}</p>}
          {!error && !data?.available && <div className="mt-6 rounded-2xl border border-dashed border-[#dedce9] bg-[#fbfbf9] p-8 text-center"><BarChart3 size={30} className="mx-auto text-[#7770e8]"/><p className="mt-4 font-bold">No evaluation results available</p><p className="mx-auto mt-2 max-w-lg text-xs leading-6 text-[#858895]">{data?.message || "Run the evaluation runner for trained checkpoints. The API will discover results/experiments/*/retrieval_metrics.json automatically."}</p></div>}
          {data?.available && models.length===0 && <p className="mt-6 rounded-xl bg-[#fbfbf9] p-5 text-sm text-[#858895]">The evaluation file was found, but it does not contain model results in the expected format.</p>}
          {models.map((model,index)=><article key={model.experiment || model.name || index} className="mt-6 rounded-2xl border border-[#e9e7df] p-5 sm:p-6">
            <div className="flex flex-wrap items-start justify-between gap-3"><div><h3 className="text-lg font-black">{model.name || model.model_type || "Evaluated model"}</h3><p className="mt-1 text-xs text-[#858895]">{model.experiment || model.encoder_type || "Experiment"} · {model.num_images ?? "—"} validation images · {model.embedding_dim ?? "—"}-D embeddings</p></div><span className="rounded-full bg-[#eff8d9] px-3 py-1.5 text-[9px] font-extrabold uppercase tracking-wider text-[#617b2e]">{model.test_set_used === false ? "Validation only" : "Check split metadata"}</span></div>
            <div className="mt-5 grid gap-4 md:grid-cols-2"><MetricBars title="Text → Image" metrics={model.text_to_image}/><MetricBars title="Image → Text" metrics={model.image_to_text}/></div>
            <p className="mt-4 text-[10px] text-[#999ba5]">Source: {model.source || data?.source || "evaluation artifact"} · API response latency is measured on each live search response, not in this offline evaluation file.</p>
          </article>)}
        </section>
      </section>
    </main>
  );
}
